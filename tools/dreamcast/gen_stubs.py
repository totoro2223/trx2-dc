#!/usr/bin/env python3
"""Generates do-nothing definitions for symbols the Dreamcast link is missing.

Reads a linker log, finds each undefined symbol's declaration in the headers
under src/trx, and writes a C file defining it. The result is a starting point
for the platform layer, not something to regenerate over hand-written code.

    gen_stubs.py LOG OUT.c --prefix Output_ --prefix TRX_GL_ ...
"""

import argparse
import re
from pathlib import Path

SRC = Path(__file__).resolve().parents[2] / "src"


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    return text


def load_headers() -> dict[Path, str]:
    headers = {}
    for path in (SRC / "trx").rglob("*.h"):
        text = strip_comments(path.read_text(encoding="utf-8", errors="replace"))
        # drop preprocessor lines (including continued macro bodies)
        text = re.sub(r"^\s*#(?:[^\n]*\\\n)*[^\n]*", " ", text, flags=re.M)
        headers[path] = text
    return headers


def find_declaration(name: str, headers: dict[Path, str]):
    func_re = re.compile(
        r"(?:^|[;{}])\s*([A-Za-z_][\w\s\*]*?[\s\*])" + re.escape(name) + r"\s*\(",
        re.S,
    )
    var_re = re.compile(
        r"\bextern\s+([^;]*?[\s\*])" + re.escape(name) + r"\s*(\[[^\]]*\])?\s*;"
    )
    for path, text in headers.items():
        m = var_re.search(text)
        if m:
            return ("var", path, " ".join(m.group(1).split()), m.group(2) or "")
        m = func_re.search(text)
        if m:
            start = m.end()
            depth = 1
            i = start
            while depth and i < len(text):
                if text[i] == "(":
                    depth += 1
                elif text[i] == ")":
                    depth -= 1
                i += 1
            params = " ".join(text[start : i - 1].split())
            ret = " ".join(m.group(1).split())
            ret = re.sub(r"^(?:extern|NODISCARD)\s+", "", ret)
            return ("func", path, ret, params)
    return None


def body_for(ret: str, name: str, fail_names: set[str]) -> str:
    head = "{\n    DC_STUB();\n"
    if ret == "void":
        return head + "}\n"
    if "*" in ret:
        return head + "    return nullptr;\n}\n"
    if ret == "RESULT":
        if name in fail_names:
            return head + '    return FAIL("%s: not available on the Dreamcast", __func__);\n}\n'
        return head + "    return OK;\n}\n"
    return head + "    return (%s) {};\n}\n" % ret


def name_params(params: str) -> str:
    # Parameters that only give a type (e.g. "int32_t") still compile in C23.
    return params or "void"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("log")
    parser.add_argument("out")
    parser.add_argument("--prefix", action="append", default=[])
    parser.add_argument("--exclude-prefix", action="append", default=[])
    parser.add_argument(
        "--fail", action="append", default=[],
        help="RESULT functions that should report failure",
    )
    parser.add_argument("--title", default="Dreamcast stubs")
    args = parser.parse_args()

    log = Path(args.log).read_text(encoding="utf-8", errors="replace")
    symbols = sorted(set(re.findall(r"undefined reference to `([^']+)'", log)))
    symbols = [
        s for s in symbols
        if any(s.startswith(p) for p in args.prefix)
        and not any(s.startswith(p) for p in args.exclude_prefix)
    ]

    headers = load_headers()
    includes = set()
    chunks = []
    missing = []
    for name in symbols:
        decl = find_declaration(name, headers)
        if decl is None:
            missing.append(name)
            continue
        kind, path, ret, extra = decl
        includes.add(path.relative_to(SRC).as_posix())
        if kind == "var":
            chunks.append(f"{ret} {name}{extra};\n")
        else:
            chunks.append(
                f"{ret} {name}({name_params(extra)})\n"
                + body_for(ret, name, set(args.fail))
            )

    out = [f"// {args.title}.\n// Generated by tools/dreamcast/gen_stubs.py, then maintained by hand.\n\n"]
    out.append('#include "stub.h"\n\n')
    out += [f"#include <{inc}>\n" for inc in sorted(includes)]
    out.append("\n")
    out.append("\n".join(chunks))
    Path(args.out).write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"{len(chunks)} stubs written to {args.out}")
    for name in missing:
        print(f"no declaration found: {name}")


if __name__ == "__main__":
    main()
